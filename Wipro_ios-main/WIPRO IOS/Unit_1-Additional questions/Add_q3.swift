// 3.1: Integer division
print(7 / 2)

// 3.2: Remainder
print(7 % 2)

// 3.3: Negative remainder
print(-7 % 3)

// 3.4: Floating-point division
print(7.0 / 2)

// 3.5: Operator precedence
print(10 - 2 * 3 + 4 / 2)

// 3.6: Logical operators
print(5 > 3 && 2 > 4 || true)

// 3.7: Left bit shift
print(1 << 3)

// 3.8: Bitwise AND, OR, XOR
print(6 & 3, 6 | 3, 6 ^ 3)

// 3.9: Overflow addition
let x: UInt8 = 255
print(x &+ 1)